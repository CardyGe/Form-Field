// Builds the Print screen's blue-noise threshold tile.
// Run: node scripts/make-blue-noise.mjs
//
// Void-and-cluster (Ulichney 1993) on a 64x64 torus with a Gaussian of sigma
// 1.5. Every pixel gets a rank 0..4095, stored as rank >> 4, so each byte value
// 0..255 appears exactly 16 times. Seeded, so the output is the same every run.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SIZE = 64, N = SIZE * SIZE, SIGMA = 1.5, SEED = 0x5eed1e;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Toroidal Gaussian: kernel[dy * SIZE + dx] for wrapped offsets.
const kernel = new Float64Array(N);
for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
  const dx = Math.min(x, SIZE - x), dy = Math.min(y, SIZE - y);
  kernel[y * SIZE + x] = Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA));
}

function addEnergy(energy, index, sign) {
  const px = index % SIZE, py = (index / SIZE) | 0;
  for (let y = 0; y < SIZE; y++) {
    const ky = ((y - py + SIZE) % SIZE) * SIZE;
    for (let x = 0; x < SIZE; x++) energy[y * SIZE + x] += sign * kernel[ky + ((x - px + SIZE) % SIZE)];
  }
}
/** Tightest cluster: the set pixel with the most energy. Ties go to the lowest index. */
function tightest(bits, energy) {
  let best = -1, value = -Infinity;
  for (let i = 0; i < N; i++) if (bits[i] && energy[i] > value) { value = energy[i]; best = i; }
  return best;
}
/** Largest void: the empty pixel with the least energy. */
function largestVoid(bits, energy) {
  let best = -1, value = Infinity;
  for (let i = 0; i < N; i++) if (!bits[i] && energy[i] < value) { value = energy[i]; best = i; }
  return best;
}
function energyOf(bits) {
  const energy = new Float64Array(N);
  for (let i = 0; i < N; i++) if (bits[i]) addEnergy(energy, i, 1);
  return energy;
}

// Initial binary pattern: a tenth of the pixels, then relaxed until the
// tightest cluster and the largest void are the same pixel.
const random = mulberry32(SEED), initial = new Uint8Array(N);
let ones = 0;
while (ones < N / 10) { const i = Math.floor(random() * N); if (!initial[i]) { initial[i] = 1; ones++; } }
{
  const energy = energyOf(initial);
  for (;;) {
    const cluster = tightest(initial, energy);
    initial[cluster] = 0; addEnergy(energy, cluster, -1);
    const hole = largestVoid(initial, energy);
    initial[hole] = 1; addEnergy(energy, hole, 1);
    if (hole === cluster) break;
  }
}

const rank = new Int32Array(N).fill(-1);
// Phase 1: rank the initial pattern's pixels by removing tightest clusters.
{
  const bits = initial.slice(), energy = energyOf(bits);
  for (let r = ones - 1; r >= 0; r--) { const i = tightest(bits, energy); bits[i] = 0; addEnergy(energy, i, -1); rank[i] = r; }
}
// Phases 2 and 3: fill the largest voids up to every pixel. (Past half, the
// tightest cluster of empty pixels is the same pixel as the largest void.)
{
  const bits = initial.slice(), energy = energyOf(bits);
  for (let r = ones; r < N; r++) { const i = largestVoid(bits, energy); bits[i] = 1; addEnergy(energy, i, 1); rank[i] = r; }
}

const bytes = Uint8Array.from(rank, r => r >> 4);
const base64 = Buffer.from(bytes).toString('base64');
const lines = base64.match(/.{1,100}/g).map(line => `  '${line}'`).join(',\n');
const source = `// Generated by scripts/make-blue-noise.mjs. Do not edit by hand.
// A 64x64 void-and-cluster blue-noise tile (Gaussian sigma 1.5, torus), one
// byte per texel, row by row: each value 0..255 appears 16 times.
export const BLUE_NOISE_BASE64 = [
${lines},
].join('');
`;
await fs.writeFile(path.join(root, 'src/rendering/blue-noise-data.ts'), source);
console.log(`Wrote src/rendering/blue-noise-data.ts (${bytes.length} bytes, seed ${SEED.toString(16)}).`);
